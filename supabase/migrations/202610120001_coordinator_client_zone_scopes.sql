-- Coordinator client + zone access scopes.
-- Apply this migration in Supabase SQL Editor. Existing permissive role/workflow
-- policies remain in place; these RESTRICTIVE policies additionally enforce scope.
create table if not exists public.coordinator_case_scopes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.user_profiles(user_id) on delete cascade,
  client_id text not null,
  zone text not null,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint coordinator_case_scopes_unique unique (user_id, client_id, zone),
  constraint coordinator_case_scopes_zone_nonempty check (length(trim(zone)) > 0)
);

alter table public.coordinator_case_scopes enable row level security;
grant select, insert, delete on public.coordinator_case_scopes to authenticated;
grant usage, select on sequence public.coordinator_case_scopes_id_seq to authenticated;

drop policy if exists "active admins manage coordinator scopes" on public.coordinator_case_scopes;
create policy "active admins manage coordinator scopes"
on public.coordinator_case_scopes
for all
to authenticated
using (
  exists (
    select 1 from public.user_profiles up
    where up.user_id = (select auth.uid())
      and up.role = 'Admin'
      and up.is_active = true
  )
)
with check (
  exists (
    select 1 from public.user_profiles up
    where up.user_id = (select auth.uid())
      and up.role = 'Admin'
      and up.is_active = true
  )
);

-- Do not let a Coordinator read or change cases outside their assigned
-- client + zone pairs. Other active roles keep their existing workflow policies.
-- The profile-active check also prevents inactive/missing profiles from using
-- an otherwise permissive legacy cases policy.
drop policy if exists "case scope gate select" on public.cases;
create policy "case scope gate select"
on public.cases as restrictive
for select to authenticated
using (
  exists (
    select 1
    from public.user_profiles up
    where up.user_id = (select auth.uid())
      and up.is_active = true
      and (
        up.role <> 'Coordinator'
        or exists (
          select 1
          from public.coordinator_case_scopes s
          where s.user_id = up.user_id
            and s.client_id = public.cases.client_id::text
            and lower(trim(s.zone)) = lower(trim(public.cases.zone))
        )
      )
  )
);

