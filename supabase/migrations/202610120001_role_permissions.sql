-- CarDekho portal: role-based module permissions
create table if not exists public.role_permissions (
  id bigint generated by default as identity primary key,
  role text not null check (role in ('Admin','Coordinator','TPA','QC','Pricing')),
  module text not null,
  can_access boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (role, module)
);

alter table public.role_permissions enable row level security;

-- Only authenticated Admin profiles may view or change the permission matrix.
drop policy if exists "Admins can read role permissions" on public.role_permissions;
create policy "Admins can read role permissions"
on public.role_permissions for select to authenticated
using (
  exists (
    select 1 from public.user_profiles p
    where p.user_id = auth.uid() and p.role = 'Admin' and coalesce(p.is_active, true) = true
  )
);

drop policy if exists "Admins can insert role permissions" on public.role_permissions;
create policy "Admins can insert role permissions"
on public.role_permissions for insert to authenticated
with check (
  role <> 'Admin' and exists (
    select 1 from public.user_profiles p
    where p.user_id = auth.uid() and p.role = 'Admin' and coalesce(p.is_active, true) = true
  )
);

drop policy if exists "Admins can update role permissions" on public.role_permissions;
create policy "Admins can update role permissions"
on public.role_permissions for update to authenticated
using (
  role <> 'Admin' and exists (
    select 1 from public.user_profiles p
    where p.user_id = auth.uid() and p.role = 'Admin' and coalesce(p.is_active, true) = true
  )
)
with check (
  role <> 'Admin' and exists (
    select 1 from public.user_profiles p
    where p.user_id = auth.uid() and p.role = 'Admin' and coalesce(p.is_active, true) = true
  )
);

-- Seed every portal module so the matrix is populated on first load.
insert into public.role_permissions (role, module, can_access)
select roles.role, modules.module, (roles.role = 'Admin')
from (values ('Admin'),('Coordinator'),('TPA'),('QC'),('Pricing')) as roles(role)
cross join (values
 ('Dashboard'),('Add Lead'),('Open Lead'),('Assign'),('Reassign'),('TPA QC'),('QC'),('QC Hold'),
 ('Pricing'),('Report Generated'),('MIS'),('Case Search'),('Users'),('TPA Master'),('Client Master'),
 ('MMV Master'),('Location/Zone Master'),('Permissions'),('Audit Trail'),('Help Desk')
) as modules(module)
on conflict (role, module) do nothing;
